    @Test
    fun testAudioTrackExtensionConvenience() {
        val sampleRate = 44100f
        val channels = 2
        val numSamples = 22050

        val data = Array(channels) { c ->
            FloatArray(numSamples) { i -> sin(2.0 * PI * 440.0 * i / sampleRate).toFloat() }
        }
        val track = AudioTrack(data, sampleRate)

        // 2x speed -> duration is halved (11025 samples)

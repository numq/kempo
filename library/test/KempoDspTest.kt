    @Test
    fun testMultiChannelBufferWrapAround() {
        val channels = 2
        val capacity = 1024
        val buffer = MultiChannelBuffer(channels, capacity)

        val src = FloatArray(800) { it.toFloat() }
        val dst = FloatArray(800)

        buffer.head = 600
        buffer.write(0, 0, src, 0, 800)
        buffer.read(0, 0, dst, 0, 800)

        for (i in 0 until 800) {
            assertEquals(src[i], dst[i], "Mismatch at index $i during circular buffer wrap-around")
        }
    }

    @Test
    fun testMultiChannelBufferAccumulateAndClear() {
        val channels = 2
        val buffer = MultiChannelBuffer(channels, 512)

        val dataA = FloatArray(256) { 1.5f }
        val dataB = FloatArray(256) { 2.5f }
        val out = FloatArray(256)

        buffer.write(1, 0, dataA, 0, 256)
        buffer.add(1, 0, dataB, 0, 256)
        buffer.read(1, 0, out, 0, 256, clearAfterRead = true)

        for (i in 0 until 256) {
            assertEquals(4.0f, out[i], 1e-6f, "Addition mismatch at $i")
        }

        // Verify that clearAfterRead zeroed out the ring buffer
        val checkZero = FloatArray(256)
        buffer.read(1, 0, checkZero, 0, 256)
        for (i in 0 until 256) {
            assertEquals(0.0f, checkZero[i], 1e-6f, "Buffer was not cleared after read at $i")
        }
    }


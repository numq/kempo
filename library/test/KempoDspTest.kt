    @Test
    fun testIdentityStretchSnr() {
        val sampleRate = 44100f
        val channels = 1
        val numSamples = 44100
        val stretch = KempoStretch()
        stretch.presetDefault(channels, sampleRate)
        stretch.setTransposeSemitones(0f)

        val input = Array(channels) {
            FloatArray(numSamples) { i ->
                sin(2.0 * PI * 440.0 * i / sampleRate).toFloat()
            }
        }
        val output = Array(channels) { FloatArray(numSamples) }

        val success = stretch.exact(input, numSamples, output, numSamples)
        assertTrue(success, "Exact processing returned false")

        val margin = (sampleRate * 0.15f).toInt()
        val evalStart = margin
        val evalEnd = numSamples - margin
        val evalLen = evalEnd - evalStart

        var bestLag = 0
        var maxCorr = Double.NEGATIVE_INFINITY
        for (lag in -64..64) {
            var corr = 0.0
            for (i in 0 until evalLen) {
                val inVal = input[0][evalStart + i].toDouble()
                val outVal = output[0][evalStart + i + lag].toDouble()
                corr += inVal * outVal
            }
            if (corr > maxCorr) {
                maxCorr = corr
                bestLag = lag
            }
        }

        var signalPower = 0.0
        var noisePower = 0.0
        for (i in 0 until evalLen) {
            val original = input[0][evalStart + i].toDouble()
            val reconstructed = output[0][evalStart + i + bestLag].toDouble()
            val diff = original - reconstructed

            signalPower += original * original
            noisePower += diff * diff
        }

        val snr = 10.0 * log10(signalPower / (noisePower + 1e-15))
        assertTrue(
            snr > 30.0, "SNR for aligned identity time-stretch is too low: $snr dB (best lag: $bestLag)"
        )
    }

    @Test
    fun testPitchShiftFrequencyShiftAccuracy() {
        val sampleRate = 44100f
        val channels = 1
        val numSamples = 44100
        val baseFreq = 440.0
        val semitones = 12.0f // One octave up: 440 Hz -> 880 Hz

        val input = Array(channels) {
            FloatArray(numSamples) { i ->
                sin(2.0 * PI * baseFreq * i / sampleRate).toFloat()
            }
        }
        val output = Array(channels) { FloatArray(numSamples) }

        val stretch = KempoStretch()
        stretch.presetDefault(channels, sampleRate)
        stretch.setTransposeSemitones(semitones)
        val success = stretch.exact(input, numSamples, output, numSamples)
        assertTrue(success)

        // Evaluate zero-crossings in stable region to verify fundamental frequency
        val evalStart = (sampleRate * 0.25f).toInt()
        val evalEnd = (sampleRate * 0.75f).toInt()
        var zeroCrossings = 0
        for (i in evalStart until evalEnd - 1) {
            if (output[0][i] <= 0f && output[0][i + 1] > 0f) {
                zeroCrossings++
            }
        }

        val durationSec = (evalEnd - evalStart).toDouble() / sampleRate
        val measuredFreq = zeroCrossings / durationSec
        val expectedFreq = 880.0

        assertTrue(
            abs(measuredFreq - expectedFreq) < 15.0, "Expected shifted frequency ~880 Hz, but measured $measuredFreq Hz"
        )
    }

    @Test
    fun testExtremeStretchingNoNanOrInfinity() {
        val sampleRate = 44100f
        val channels = 2
        val inSamples = 22050
        val rng = Random(42)

        val input = Array(channels) {
            FloatArray(inSamples) { rng.nextFloat() * 2f - 1f }
        }

        val testRatios = floatArrayOf(0.25f, 0.5f, 1.5f, 3.0f)
        for (ratio in testRatios) {
            val outSamples = (inSamples / ratio).toInt().coerceAtLeast(1)
            val output = Array(channels) { FloatArray(outSamples) }

            val stretch = KempoStretch()
            stretch.presetDefault(channels, sampleRate)
            stretch.setTransposeSemitones(-7.0f)
            stretch.setFormantSemitones(5.0f)

            val success = stretch.exact(input, inSamples, output, outSamples)
            assertTrue(success, "Exact processing failed for ratio $ratio")

            for (c in 0 until channels) {
                for (i in 0 until outSamples) {
                    val s = output[c][i]
                    assertFalse(s.isNaN(), "Output contains NaN at ratio $ratio, channel $c, index $i")
                    assertFalse(s.isInfinite(), "Output contains Infinity at ratio $ratio, channel $c, index $i")
                }
            }
        }
    }

    @Test
    fun testStereoPhaseCoherence() {
        val sampleRate = 44100f
        val channels = 2
        val numSamples = 44100
        val phaseShift = PI / 4.0 // 45-degree inter-channel phase difference

        val input = Array(channels) { c ->
            FloatArray(numSamples) { i ->
                sin(2.0 * PI * 440.0 * i / sampleRate + c * phaseShift).toFloat()
            }
        }
        val output = Array(channels) { FloatArray(numSamples) }

        val stretch = KempoStretch()
        stretch.presetDefault(channels, sampleRate)
        stretch.setTransposeSemitones(3.0f)
        stretch.exact(input, numSamples, output, numSamples)

        val evalStart = (sampleRate * 0.3f).toInt()
        val evalEnd = (sampleRate * 0.7f).toInt()
        var correlation = 0.0
        var normL = 0.0
        var normR = 0.0

        for (i in evalStart until evalEnd) {
            val l = output[0][i].toDouble()
            val r = output[1][i].toDouble()
            correlation += l * r
            normL += l * l
            normR += r * r
        }

        val normalizedCrossCorr = correlation / (sqrt(normL * normR) + 1e-15)
        val expectedCrossCorr = cos(phaseShift) // cos(45 deg) ~= 0.7071

        assertEquals(
            expectedCrossCorr, normalizedCrossCorr, 0.08, "Stereo imaging collapsed or degraded after phase vocoder"
        )
    }

    @Test
    fun testRealtimeStreamingContinuity() {
        val sampleRate = 44100f
        val channels = 1
        val stretch = KempoStretch()
        stretch.presetDefault(channels, sampleRate)

        val outBlockSize = stretch.stft.defaultInterval()
        val inBlockSize = outBlockSize // 1.0x ratio

        val inBlock = Array(channels) { FloatArray(inBlockSize) }
        val outBlock = Array(channels) { FloatArray(outBlockSize) }

        var phase = 0.0
        val phaseStep = 2.0 * PI * 440.0 / sampleRate

        // Stream 50 consecutive blocks without resetting
        var lastSample = 0f
        for (b in 0 until 50) {
            for (i in 0 until inBlockSize) {
                inBlock[0][i] = sin(phase).toFloat()
                phase += phaseStep
            }

            stretch.process(inBlock, inBlockSize, outBlock, outBlockSize)

            if (b > 10) {
                // Verify continuous waveform without sudden step jumps across boundaries
                val step = abs(outBlock[0][0] - lastSample)
                assertTrue(
                    step < 0.35f, "Discontinuity click detected at boundary of block $b: step was $step"
                )
            }
            lastSample = outBlock[0][outBlockSize - 1]
        }
    }


        assertEquals(2, stretched.numChannels)
        assertEquals(numSamples / 2, stretched.numSamples)
        assertEquals(sampleRate, stretched.sampleRate)
    }

    @Test
    fun testPcmConverterRoundtrip() {
        val channels = 2
        val sampleRate = 48000f
        val numSamples = 1000

        val originalData = Array(channels) { FloatArray(numSamples) { (it / 1000f) * 1.8f - 0.9f } }
        val originalTrack = AudioTrack(originalData, sampleRate)

        val bytes = PcmConverter.toPcm16(originalTrack, isLittleEndian = true)
        val decodedTrack = PcmConverter.fromPcm16(bytes, channels, sampleRate, isLittleEndian = true)

        assertEquals(originalTrack.numChannels, decodedTrack.numChannels)
        assertEquals(originalTrack.numSamples, decodedTrack.numSamples)

        // Verify 16-bit quantization error (|error| < 1 / 32768)
        for (c in 0 until channels) {
            for (i in 0 until numSamples) {
                val expected = originalData[c][i]
                val actual = decodedTrack.channels[c][i]
                assertEquals(expected, actual, 1f / 32767f, "PCM quantization mismatch at channel $c, sample $i")
            }
        }
    }

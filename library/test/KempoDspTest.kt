    @Test
    fun testModifiedRealFftSymmetryAndRoundtrip() {
        val sizes = intArrayOf(64, 256, 1024, 2048)
        val rng = Random(1337)

        for (n in sizes) {
            val mrfft = ModifiedRealFFT(n)
            val hSize = n / 2
            val input = FloatArray(n) { rng.nextFloat() * 2f - 1f }
            val outRe = FloatArray(hSize)
            val outIm = FloatArray(hSize)
            val reconstructed = FloatArray(n)

            mrfft.fft(input, inOffset = 0, outRe = outRe, outIm = outIm, outOffset = 0)
            mrfft.ifft(outRe, outIm, reconstructed, outOffset = 0, inOffset = 0)

            val invN = 1f / n
            var maxError = 0f
            for (i in 0 until n) {
                val diff = abs(input[i] - reconstructed[i] * invN)
                maxError = max(maxError, diff)
            }

            assertTrue(
                maxError < 1e-4f, "ModifiedRealFFT roundtrip error exceeds tolerance for size $n: $maxError"
            )
        }
    }

    @Test
    fun testWindowPerfectReconstructionWola() {
        val windowSizes = intArrayOf(512, 1024, 2048)
        val hops = intArrayOf(128, 256, 512)

        for (w in windowSizes) {
            for (r in hops) {
                if (r > w / 2) continue
                val windowed = WindowedFFT()
                windowed.setKaiser(w, r, rotateToCenter = true)
                val window = windowed.window

                for (i in 0 until r) {
                    var sumSq = 0.0
                    var idx = i
                    while (idx < w) {
                        sumSq += window[idx].toDouble() * window[idx].toDouble()
                        idx += r
                    }
                    assertEquals(
                        1.0, sumSq, 1e-4, "WOLA condition failed for window $w and hop $r at phase $i"
                    )
                }
            }
        }
    }


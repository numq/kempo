    @Test
    fun testFastFftInvertibilityPowerOfTwo() {
        val sizes = intArrayOf(32, 64, 128, 256, 512, 1024, 2048, 4096)
        val rng = Random(42)

        for (n in sizes) {
            val fft = FastFft(n)
            val inRe = FloatArray(n) { rng.nextFloat() * 2f - 1f }
            val inIm = FloatArray(n) { rng.nextFloat() * 2f - 1f }
            val specRe = FloatArray(n)
            val specIm = FloatArray(n)
            val outRe = FloatArray(n)
            val outIm = FloatArray(n)

            fft.fft(inRe, inIm, specRe, specIm)
            fft.ifft(specRe, specIm, outRe, outIm)

            val invN = 1f / n
            var maxError = 0f
            for (i in 0 until n) {
                val diffRe = abs(inRe[i] - outRe[i] * invN)
                val diffIm = abs(inIm[i] - outIm[i] * invN)
                maxError = max(maxError, max(diffRe, diffIm))
            }

            assertTrue(
                maxError < 1e-4f, "FFT roundtrip error exceeds tolerance for power-of-two size $n: $maxError"
            )
        }
    }

